import { appModules, sourceModules } from "./registry.js";

/** Known operator-key limits. These build counts do not establish hosted deployment or liveness. */
export const HOSTED_LIMITS: Record<string, string> = {
  nta: "NTA realtime needs an operator key.",
  logainm: "Logainm needs a Gaois operator account and API key."
};

/** ireland_catalogue, ireland_describe, ireland_call, ireland_query, ireland_about. */
export const META_TOOLS = 5;
export const PROMPTS = ["area_profile", "commute_check", "compare_counties"] as const;

export interface Counts {
  sources: number;
  hosted_working: number;
  hosted_limited: string[];
  operations: number;
  source_operations: number;
  cross_operations: number;
  default_tools: number;
  all_tools: number;
  prompts: number;
  dataset_cards: number;
}

export function computeCounts(): Counts {
  const { modules, extraTools } = appModules();
  const ops = modules.flatMap((m) => m.tools);
  const sourceOps = sourceModules.reduce((sum, m) => sum + m.tools.length, 0);
  return {
    sources: sourceModules.length,
    hosted_working: sourceModules.length - Object.keys(HOSTED_LIMITS).length,
    hosted_limited: Object.keys(HOSTED_LIMITS),
    operations: ops.length,
    source_operations: sourceOps,
    cross_operations: ops.length - sourceOps,
    default_tools: META_TOOLS + extraTools.length + ops.filter((t) => t.pinned).length,
    all_tools: META_TOOLS + extraTools.length + ops.length,
    prompts: PROMPTS.length,
    dataset_cards: sourceModules.filter((m) => m.card).length
  };
}

export const COUNTS_START = "<!-- counts:start (generated by `npm run counts`; CI checks it) -->";
export const COUNTS_END = "<!-- counts:end -->";

/** The README's definitions table. */
export function renderCounts(c: Counts): string {
  const limited = Object.values(HOSTED_LIMITS).join(" ");
  return [
    COUNTS_START,
    "| Count | Value | Definition |",
    "| --- | ---: | --- |",
    `| Data sources | ${c.sources} | Upstream public-data sources, one module each. The \`cross\` combiner is not a source. |`,
    `| Available without an operator key | ${c.hosted_working} of ${c.sources} | ${limited} |`,
    `| Catalogue operations | ${c.operations} | ${c.source_operations} source operations plus ${c.cross_operations} cross-source ones (\`list_sources\`, \`nearby\`, \`ireland_snapshot\`, \`ireland_resolve_place\`), all callable through \`ireland_call\`. |`,
    `| Default tools | ${c.default_tools} | What \`tools/list\` returns: ${META_TOOLS} meta tools plus \`search\`, \`fetch\`, \`nearby\` and \`ireland_resolve_place\`. |`,
    `| Tools with \`?toolsets=all\` | ${c.all_tools} | Every operation as a typed tool, plus the ${META_TOOLS} meta tools, \`search\` and \`fetch\`. |`,
    `| Prompts | ${c.prompts} | ${PROMPTS.map((p) => `\`${p}\``).join(", ")}. |`,
    `| Dataset cards | ${c.dataset_cards} of ${c.sources} | Sources with a card (topics, geography levels, time coverage, join keys) that \`ireland_catalogue\` filters on. See [dataset cards](docs/dataset-cards.md). |`,
    COUNTS_END
  ].join("\n");
}

/** The README's one-line live-ops summary, taken from docs/live-all-ops.md. */
export function liveOpsSummary(report: string): string {
  const generated = report.match(/^Generated: (\d{4}-\d{2}-\d{2})/m)?.[1];
  // DEGRADED was added later; older reports omit it.
  const line = report.match(/^Operations: (\d+) PASS, (\d+) NOT_CONFIGURED, (\d+) HOSTED_BLOCKED, (?:(\d+) DEGRADED, )?(\d+) FAIL\./m);
  if (!generated || !line) throw new Error("docs/live-all-ops.md has no Generated/Operations summary line.");
  const [pass, notConfigured, blocked, degraded, fail] = line.slice(1).map((n) => Number(n ?? 0)) as [number, number, number, number, number];
  const total = pass + notConfigured + blocked + degraded + fail;
  const notes = [
    `${notConfigured} need an operator key (NTA, Logainm)`,
    ...(blocked ? [`${blocked} blocked from Azure IPs`] : []),
    ...(degraded ? [`${degraded} degraded (stale or partial)`] : [])
  ];
  return `[docs/live-all-ops.md](docs/live-all-ops.md) (${generated}): ${pass} of ${total} pass, ${fail} fail; ${notes.join(", ")}.`;
}
